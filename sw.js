/* =============================================================================
   sw.js — offline-first service worker. Job A2.

   Strategy map
     navigation (the SPA shell) network-first, falls back to cached index.html
     vault-data.js                stale-while-revalidate (instant, then fresh)
     lesson / reference HTML      stale-while-revalidate
     everything else same-origin  cache-first, filled on demand
     SUPABASE + any cross-origin  NETWORK ONLY, never cached (API data must
                                  never be served from a stale cache)

   Cache hygiene
     · one versioned cache per release; every other engram-* cache is deleted
       on activate
     · install pre-caches the shell with individual, tolerant adds so one
       missing optional file (theme.css before the design job lands, a
       not-yet-generated vault-data.js) can never break installation
     · never cache non-GET, Range requests, or opaque cross-origin responses

   Bump CACHE_VERSION on every deploy (js/config.js APP_VERSION should match).
   ========================================================================== */

