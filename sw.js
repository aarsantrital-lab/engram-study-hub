/* ---------------------------------------------------------------------------
   Install
   ------------------------------------------------------------------------ */

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    const addAll = async (list, loud) => {
      const results = await Promise.allSettled(list.map((p) => cache.add(new Request(abs(p), { cache: 'reload' }))));
      const failed = list.filter((_, i) => results[i].status === 'rejected');
      if (failed.length && loud) console.warn('[sw] precache misses:', failed.join(', '));
      return failed;
    };
    await addAll(PRECACHE_CORE, true);
    await addAll(PRECACHE_OPTIONAL, false);
    // Do NOT skipWaiting automatically — the page offers the user an
    // "Update now" action, which posts SKIP_WAITING below.
  })());
});

/* ---------------------------------------------------------------------------
   Activate — drop every older engram cache
   ------------------------------------------------------------------------ */

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names
      .filter((n) => n.startsWith(CACHE_PREFIX) && n !== CACHE_NAME)
      .map((n) => caches.delete(n)));
    if (self.registration.navigationPreload) {
      try { await self.registration.navigationPreload.enable(); } catch (_) { /* optional */ }
    }
    await self.clients.claim();
  })());
});

/* ---------------------------------------------------------------------------
   Routing helpers
   ------------------------------------------------------------------------ */

/** Origins whose responses must NEVER be cached or intercepted. */
function isNeverCache(url) {
  const host = url.hostname;
  return (
    host.endsWith('supabase.co') ||
    host.endsWith('supabase.in') ||
    host.endsWith('supabase.net') ||
    host.includes('supabase') ||
    url.pathname.startsWith('/rest/v1/') ||
    url.pathname.startsWith('/auth/v1/') ||
    url.pathname.startsWith('/realtime/v1/') ||
    url.pathname.startsWith('/storage/v1/') ||
    url.protocol === 'ws:' || url.protocol === 'wss:'
  );
}

function isVaultData(url) {
  return /(^|\/)vault-data\.js(\?.*)?$/.test(url.pathname);
}

/** Lesson / cheatsheet HTML lives under assets/ and is regenerated by sync. */
function isContentHtml(url) {
  return /\.html?$/i.test(url.pathname) && /\/assets\//.test(url.pathname);
}

/* ---------------------------------------------------------------------------
   Fetch
   ------------------------------------------------------------------------ */

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  if (req.headers.has('range')) return;

  let url;
  try { url = new URL(req.url); } catch (_) { return; }

  if (url.protocol !== 'http:' && url.protocol !== 'https:') return;

  // 1. Supabase / any API: straight to the network, never cached.
  if (isNeverCache(url)) return;

  // 2. Cross-origin: pass through (this app ships zero external origins).
  if (url.origin !== self.location.origin) return;

  // 3. SPA navigations: network-first so a redeploy is picked up, with the
  //    cached shell as the offline fallback.
  if (req.mode === 'navigate') {
    event.respondWith(networkFirstShell(event));
    return;
  }

  // 4. Data + lesson HTML: stale-while-revalidate.
  if (isVaultData(url) || isContentHtml(url)) {
    event.respondWith(staleWhileRevalidate(req, isVaultData(url)));
    return;
  }

  // 5. Everything else same-origin: cache-first.
  event.respondWith(cacheFirst(req));
});

async function networkFirstShell(event) {
  const cache = await caches.open(CACHE_NAME);
  try {
    const preload = event.preloadResponse ? await event.preloadResponse : null;
    const res = preload || await fetch(event.request);
    if (res && res.ok) cache.put(abs('index.html'), res.clone());
    return res;
  } catch (_) {
    return (await cache.match(abs('index.html'))) ||
           (await cache.match(abs('./'))) ||
           new Response('<h1>Offline</h1><p>Engram has not been cached yet. Reconnect once, then it works offline.</p>',
             { status: 503, headers: { 'Content-Type': 'text/html; charset=utf-8' } });
  }
}

async function staleWhileRevalidate(req, notifyOnChange) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(req);

  const network = fetch(req).then(async (res) => {
    if (res && res.ok && res.type !== 'opaque') {
      const changed = notifyOnChange && cached ? await bodiesDiffer(cached.clone(), res.clone()) : false;
      await cache.put(req, res.clone());
      if (changed) broadcast({ type: 'VAULT_UPDATED', url: req.url });
    }
    return res;
  }).catch(() => null);

  if (cached) { network; return cached; }
  const fresh = await network;
  return fresh || new Response('', { status: 504, statusText: 'Offline and not cached' });
}

async function cacheFirst(req) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(req);
  if (cached) return cached;
  try {
    const res = await fetch(req);
    if (res && res.ok && res.type !== 'opaque') cache.put(req, res.clone());
    return res;
  } catch (_) {
    // 504, NEVER the shell. This path handles every same-origin GET — JSON,
    // SVG, JS — not just navigations (those go through networkFirstShell, which has
    // its own index.html fallback). Answering a missed data/*.json with a 200
    // text/html shell made `res.ok` true and `res.json()` throw a SyntaxError
    // somewhere far away, hiding "you are offline and this was never cached"
    // behind a parse error. An honest 504 lets a caller say the true thing.
    return new Response('', { status: 504, statusText: 'Offline and not cached' });
  }
}

async function bodiesDiffer(a, b) {
  try {
    const [ta, tb] = await Promise.all([a.text(), b.text()]);
    return ta !== tb;
  } catch (_) { return false; }
}

function broadcast(message) {
  self.clients.matchAll({ type: 'window' }).then((clients) => {
    for (const client of clients) { try { client.postMessage(message); } catch (_) { /* gone */ } }
  });
}

/* ---------------------------------------------------------------------------
   Messages from the page
   ------------------------------------------------------------------------ */

self.addEventListener('message', (event) => {
  const msg = event.data || {};
  if (msg.type === 'SKIP_WAITING') { self.skipWaiting(); return; }
  if (msg.type === 'CLEAR_CACHES') {
    event.waitUntil((async () => {
      const names = await caches.keys();
      await Promise.all(names.filter((n) => n.startsWith(CACHE_PREFIX)).map((n) => caches.delete(n)));
      broadcast({ type: 'CACHES_CLEARED' });
    })());
    return;
  }
  if (msg.type === 'VERSION') {
    if (event.source) event.source.postMessage({ type: 'VERSION', version: CACHE_VERSION });
  }
});
