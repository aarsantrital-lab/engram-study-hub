/* =============================================================================
   js/vault.js — normalised, always-safe access to window.VAULT_DATA.
   Job A2. LEAF MODULE: imports nothing.

   `vault-data.js` is generated by generate_data.py and loaded as a CLASSIC
   script before the module graph (it sets window.VAULT_DATA). It is allowed to
   be missing — the hub MUST still boot (build-constraints §2). Every accessor
   here returns an empty-but-valid structure in that case; nothing throws.

   Schema 2 render contract (build-constraints §2, additive changes only):
     { schema, counts, topics: [{
         id, name, subject, unit, badge, description,
         flashcards: [{id, q, a, source}],
         notes:      [{title, body, path}],
         docs:       [{title, kind, url}],
         assets:     [...],
         mindmap:    {label, children, cardId?},
         updated
       }] }
   ========================================================================== */

export const VAULT_SCHEMA = 2;

/** The shape every accessor falls back to. Frozen so nobody mutates it. */
export const EMPTY_VAULT = Object.freeze({
  schema: VAULT_SCHEMA,
  topics: [],
  counts: Object.freeze({ topics: 0, flashcards: 0, notes: 0, docs: 0, assets: 0 }),
  generated: null,
  warnings: Object.freeze([]),
});

let VAULT = EMPTY_VAULT;
let missing = true;
let cardIndex = new Map();
const listeners = new Set();

/* ---------------------------------------------------------------------------
   Normalisation
   ------------------------------------------------------------------------ */

const str = (v, d) => (v === undefined || v === null ? (d || '') : String(v));
const arr = (v) => (Array.isArray(v) ? v : []);

function slug(s) {
  return str(s).toLowerCase().trim().replace(/[^\w\u0900-\u097F]+/g, '-').replace(/^-+|-+$/g, '');
}

function normalizeTopic(t, i) {
  const id = slug(t && (t.id || t.name)) || ('topic-' + i);
  const name = str(t && t.name, id);
  const subject = str(t && t.subject, 'General');
  return {
    id,
    name,
    subject,
    /** declared in MISSION.md frontmatter — NEVER keyword-sniffed (§9.4) */
    unit: str(t && t.unit, ''),
    badge: str(t && t.badge, slug(subject)),
    description: str(t && t.description, ''),
    updated: t && t.updated ? str(t.updated) : null,
    flashcards: arr(t && t.flashcards).map((c, k) => ({
      id: str(c && c.id, id + '-card-' + k),
      q: str(c && c.q),
      a: str(c && c.a),
      source: str(c && c.source, ''),
      type: str(c && c.type, ''),          // additive: card type when generator emits it
      topicId: id,
      topicName: name,
      subject,
    })).filter((c) => c.q),
    notes: arr(t && t.notes).map((n, k) => ({
      id: id + '-note-' + k,
      title: str(n && n.title, 'Note'),
      body: str(n && n.body),
      path: str(n && n.path),
      topicId: id,
    })),
    docs: arr(t && t.docs).map((d, k) => ({
      id: id + '-doc-' + k,
      title: str(d && d.title, 'Document'),
      kind: str(d && d.kind, 'doc'),       // 'lesson' | 'cheatsheet' | 'doc'
      url: str(d && d.url),
      topicId: id,
    })).filter((d) => d.url),
    assets: arr(t && t.assets),
    mindmap: (t && t.mindmap && typeof t.mindmap === 'object') ? t.mindmap : null,
    raw: t,
  };
}

function normalizeVault(raw) {
  if (!raw || typeof raw !== 'object') return { vault: EMPTY_VAULT, missing: true };
  const topics = arr(raw.topics).map(normalizeTopic);
  const counts = {
    topics: topics.length,
    flashcards: topics.reduce((n, t) => n + t.flashcards.length, 0),
    notes: topics.reduce((n, t) => n + t.notes.length, 0),
    docs: topics.reduce((n, t) => n + t.docs.length, 0),
    assets: topics.reduce((n, t) => n + t.assets.length, 0),
  };
  return {
    vault: {
      schema: Number(raw.schema) || VAULT_SCHEMA,
      topics,
      counts: Object.assign(counts, raw.counts && typeof raw.counts === 'object' ? {} : {}),
      generated: raw.generated || raw.updated || null,
      // §9.7: generator warnings must reach the student, not just the console.
      warnings: arr(raw.warnings).map((w) => str(w)),
    },
    missing: false,
  };
}

/* ---------------------------------------------------------------------------
   Public API
   ------------------------------------------------------------------------ */

/**
 * Read window.VAULT_DATA (or an injected object) and normalise it.
 * app.js calls this once at boot; tests can pass a fixture.
 * @param {Object} [raw]
 * @returns {{vault:Object, missing:boolean}}
 */
export function initVault(raw) {
  const source = raw !== undefined
    ? raw
    : (typeof window !== 'undefined' ? window.VAULT_DATA : undefined);
  const res = normalizeVault(source);
  VAULT = res.vault;
  missing = res.missing;
  cardIndex = new Map();
  for (const t of VAULT.topics) for (const c of t.flashcards) cardIndex.set(c.id, c);
  for (const fn of Array.from(listeners)) {
    try { fn(VAULT); } catch (err) { console.error('[vault] listener failed', err); }
  }
  return { vault: VAULT, missing };
}

/** The normalised vault. Always an object, never null. */
export function getVault() { return VAULT; }

/** True when vault-data.js was absent or unparseable — show the empty state. */
export function isVaultMissing() { return missing; }

/** True when the vault loaded but contains nothing yet. */
export function isVaultEmpty() { return VAULT.topics.length === 0; }

export function getTopics() { return VAULT.topics; }

export function getTopic(id) {
  const key = slug(id);
  return VAULT.topics.find((t) => t.id === key) || null;
}

/** Every flashcard across every topic, each carrying topicId/topicName/subject. */
export function getAllCards() {
  const out = [];
  for (const t of VAULT.topics) out.push(...t.flashcards);
  return out;
}

export function getCard(cardId) { return cardIndex.get(String(cardId)) || null; }

/** Docs of kind 'lesson' for a topic (or all topics when id is omitted). */
export function getLessons(topicId) {
  const topics = topicId ? [getTopic(topicId)].filter(Boolean) : VAULT.topics;
  const out = [];
  for (const t of topics) out.push(...t.docs.filter((d) => d.kind === 'lesson' || /\/lessons\//.test(d.url)));
  return out;
}

export function getDocs(topicId) {
  const t = getTopic(topicId);
  return t ? t.docs : [];
}

export function getNotes(topicId) {
  const t = getTopic(topicId);
  return t ? t.notes : [];
}

/** Distinct subjects, in first-seen order. */
export function getSubjects() {
  const seen = new Set();
  const out = [];
  for (const t of VAULT.topics) if (!seen.has(t.subject)) { seen.add(t.subject); out.push(t.subject); }
  return out;
}

export function getTopicsBySubject(subject) {
  return VAULT.topics.filter((t) => t.subject === subject);
}

export function counts() { return VAULT.counts; }

/** Generator warnings — surface these in the UI (build-constraints §9.7). */
export function warnings() { return VAULT.warnings; }

/** Subscribe to vault reloads (sw stale-while-revalidate can swap the data). */
export function onVaultChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Flatten a mindmap tree into {label, path, cardId, depth} rows. */
export function flattenMindmap(node, depth, path) {
  const out = [];
  if (!node) return out;
  const d = depth || 0;
  const p = (path || []).concat(node.label ? [String(node.label)] : []);
  if (node.label) out.push({ label: String(node.label), path: p, cardId: node.cardId || null, depth: d });
  for (const child of arr(node.children)) out.push(...flattenMindmap(child, d + 1, p));
  return out;
}

export default { initVault, getVault, getTopics, getTopic, getAllCards, getCard };
