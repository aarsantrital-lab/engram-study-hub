/* =============================================================================
   js/views/registry.js — the ONE place every view module is imported.
   Job A2.  *** FEATURE AGENTS: DO NOT EDIT THIS FILE. ***

   Replace the view FILE you own (js/views/<id>.js) and nothing else. This
   registry supplies the nav order plus fallback title/icon, so a view that
   exports only { render } still works and still appears in the tab bar.

   ---------------------------------------------------------------------------
   THE VIEW CONTRACT
   ---------------------------------------------------------------------------
     export default {
       id:    'study',                  // must equal the filename
       title: 'Study',                  // optional — registry has a fallback
       icon:  'layers',                 // optional — sprite id in assets/icons.svg
       render(el, params) { ... },      // REQUIRED. el is a fresh empty <div>
                                        // already appended to the content root.
                                        // May be async; may return a cleanup fn.
       onEnter(ctx) { ... },            // optional. after render, view visible
       onExit(ctx)  { ... },            // optional. before the view is torn down
     };

   `params` is the parsed query of the hash route (see router.js), e.g.
   #/lesson?topic=mole-concept&file=x.html -> { topic:'mole-concept', file:'x.html' }.

   `ctx` = { route, params, navigate, view, root }.

   A view may also export the object as a named `view` export instead of default.
   ========================================================================== */

import home from './home.js';
import study from './study.js';
import maps from './maps.js';
import chat from './chat.js';
import me from './me.js';
import focus from './focus.js';
import papers from './papers.js';
import stats from './stats.js';
import settings from './settings.js';
import lesson from './lesson.js';
import topic from './topic.js';

/* ---------------------------------------------------------------------------
   Nav layout — owned here so it survives any view file being rewritten.
   ------------------------------------------------------------------------ */

/** Bottom tab bar on mobile / top of the sidebar on desktop. Max 5. */
export const NAV_PRIMARY = ['home', 'study', 'maps', 'chat', 'me'];

/** The "More" sheet (mobile) / lower sidebar group (desktop). */
export const NAV_MORE = ['focus', 'papers', 'stats', 'settings'];

/** Reachable by route only — never rendered in nav. */
export const NAV_HIDDEN = ['lesson', 'topic'];

export const DEFAULT_VIEW_ID = 'home';

/** Fallback presentation, used when a view module omits title/icon. */
const META = {
  home:     { title: 'Home',       icon: 'home' },
  study:    { title: 'Study',      icon: 'layers' },
  maps:     { title: 'Maps',       icon: 'waypoints' },
  chat:     { title: 'Chat',       icon: 'message-circle' },
  me:       { title: 'Me',         icon: 'user' },
  focus:    { title: 'Focus',      icon: 'timer' },
  papers:   { title: 'Past papers',icon: 'file-text' },
  stats:    { title: 'Stats',      icon: 'trending-up' },
  settings: { title: 'Settings',   icon: 'settings' },
  lesson:   { title: 'Lesson',     icon: 'book-open' },
  topic:    { title: 'Topic',      icon: 'layers' },
};

const MODULES = { home, study, maps, chat, me, focus, papers, stats, settings, lesson, topic };

/* ---------------------------------------------------------------------------
   Normalisation — a broken view must never take the shell down with it.
   ------------------------------------------------------------------------ */

function normalize(id, mod) {
  const raw = (mod && (mod.default || mod.view || mod)) || {};
  const meta = META[id] || { title: id, icon: 'info' };
  const render = typeof raw.render === 'function'
    ? raw.render.bind(raw)
    : (el) => {
        el.textContent = 'View "' + id + '" has no render() export.';
        console.error('[registry] view "' + id + '" is missing render(el, params)');
      };
  return {
    id,
    title: typeof raw.title === 'string' && raw.title ? raw.title : meta.title,
    icon: typeof raw.icon === 'string' && raw.icon ? raw.icon : meta.icon,
    render,
    onEnter: typeof raw.onEnter === 'function' ? raw.onEnter.bind(raw) : null,
    onExit: typeof raw.onExit === 'function' ? raw.onExit.bind(raw) : null,
    module: raw,
  };
}

/** id -> normalised view object. */
export const VIEWS = Object.freeze(
  Object.fromEntries(Object.keys(MODULES).map((id) => [id, normalize(id, MODULES[id])]))
);

/** Every view, in nav order then hidden. */
export const VIEW_LIST = Object.freeze(
  [...NAV_PRIMARY, ...NAV_MORE, ...NAV_HIDDEN].filter((id) => VIEWS[id]).map((id) => VIEWS[id])
);

/** @returns {Object|null} */
export function getView(id) {
  return VIEWS[String(id || '').toLowerCase()] || null;
}

export function hasView(id) { return Boolean(getView(id)); }

/** Nav descriptors for the shell: [{id, title, icon, group}]. */
export function navItems() {
  const out = [];
  for (const id of NAV_PRIMARY) if (VIEWS[id]) out.push({ ...pick(VIEWS[id]), group: 'primary' });
  for (const id of NAV_MORE) if (VIEWS[id]) out.push({ ...pick(VIEWS[id]), group: 'more' });
  return out;
}

function pick(v) { return { id: v.id, title: v.title, icon: v.icon }; }

export default VIEWS;
